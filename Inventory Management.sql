-- 36.  Write a query to create a view named v_ProductCatalog that combines the products, subcategories, and categories tables. This view should display the product ID, name, SKU, unit price, subcategory name, and main category name for easy searching.
create view v_productcatalog as select p.productid, p.productname, p.sku, p.unitprice, c.categoryname, sb.subcategoryname  from products p join subcategories sb on sb.subcategoryid = p.subcategoryid join categories c on c.categoryid = sb.categoryid;

