-- 31. Write a query using a CTE to calculate the total item count and total line amount for each order line in SalesOrderItems. In your main query, filter the result to only show order lines where the total calculated line amount is greater than $1,000.
with calculatedorderlines as (select salesitemid, salesorderid, productid, quantity, unitprice, (quantity * unitprice) as calculatedlineamount from salesorderitems) select salesitemid, salesorderid, productid, quantity, unitprice, calculatedlineamount from calculatedorderlines where calculatedlineamount > 10000 order by calculatedlineamount desc;

-- 32. Create a CTE that joins SalesOrders with Customers to create a flat list of SalesOrderID, OrderDate, TotalAmount, and CustomerName. In the main query, select from this CTE to find all orders placed in the current year.
with orderprofiles as (select so.salesorderid, so.orderdate, so.totalamount, cu.customername from salesorders so join customers cu on cu.customerid= so.customerid) select salesorderid, orderdate, totalamount, customername from orderprofiles where extract(year from orderdate) = 2026 order by orderdate asc;

